async function loadMyListings() {
    const container = document.getElementById("myListingsContainer");
    if (!container) return;

    const mr = lang === "mr";

    if (!isLoggedIn()) {
        container.innerHTML = `
            <p>${tr("login-to-view")}</p>
            <button class="btn green" onclick="openM('loginModal')">
                ${tr("login")}
            </button>
        `;
        return;
    }

    let currentUser;

    try {
        currentUser = JSON.parse(
            localStorage.getItem("pashuCurrentUser") || "null"
        );
    } catch (error) {
        currentUser = null;
    }

    if (!currentUser || !currentUser.id) {
        container.innerHTML = `<p>${mr
            ? "वापरकर्त्याची माहिती सापडली नाही. कृपया पुन्हा लॉगिन करा."
            : "User information not found. Please login again."
        }</p>`;
        return;
    }

    container.innerHTML = `<p>${tr("loading-listings")}</p>`;

    try {
        const response = await fetch(
            `${API_BASE}/api/animals/my-listings?sellerId=${encodeURIComponent(currentUser.id)}`
        );

        const data = await response.json();

        if (!response.ok) {
            throw new Error(data.message || "Could not load listings.");
        }

        const animals = data.animals || [];

        if (animals.length === 0) {
            container.innerHTML = `<p>${tr("no-listings")}</p>`;
            return;
        }

        container.innerHTML = animals.map(animal => {
            const photo = animal.photo || "";

            const price = Number(animal.price || 0)
                .toLocaleString("en-IN");

            const category = mr
                ? (animalMr[animal.category] || animal.category || "")
                : (animal.category || "");

            const breed = mr
                ? (breedMr[animal.breed] || animal.breed || "")
                : (animal.breed || "");

            const health = mr
                ? (animal.health === "Healthy" ? "निरोगी" :
                   animal.health === "Needs Care" ? "काळजी आवश्यक" :
                   animal.health || "")
                : (animal.health || "");

            const vaccination = mr
                ? (animal.vaccination === "Vaccinated" ? "लसीकरण झालेले" :
                   animal.vaccination === "Not Vaccinated" ? "लसीकरण झालेले नाही" :
                   animal.vaccination || "")
                : (animal.vaccination || "");

            const gender = mr
                ? (animal.gender === "Male" ? "नर" :
                   animal.gender === "Female" ? "मादी" :
                   animal.gender || "")
                : (animal.gender || "");

            return `
                <article class="animal">
                    ${photo
                        ? `<img src="${photo}" alt="${mr ? "जनावराचा फोटो" : "Animal photo"}">`
                        : ""}

                    <div class="animalbody">
                        <h3>${category} - ${breed}</h3>

                        <div class="info">
                            <div><b>${tr("age")}:</b> ${animal.age || ""}</div>
                            <div><b>${tr("gender")}:</b> ${gender}</div>
                            <div><b>${tr("location")}:</b> ${animal.location || ""}</div>
                            <div><b>${tr("health")}:</b> ${health}</div>
                            <div><b>${tr("vaccination")}:</b> ${vaccination}</div>
                            <div><b>${tr("price")}:</b> ₹${price}</div>
                        </div>

                        <div class="listing-actions">
                            <button class="btn green"
                                onclick="editMyListing('${animal._id}')">
                                ${mr ? "✏️ बदला" : "✏️ Edit"}
                            </button>

                            <button class="btn"
                                onclick="deleteMyListing('${animal._id}')">
                                ${mr ? "🗑️ हटवा" : "🗑️ Delete"}
                            </button>
                        </div>
                    </div>
                </article>
            `;
        }).join("");

    } catch (error) {
        console.error("My Listings error:", error);
        container.innerHTML = `<p>${tr("listings-error")}</p>`;
    }
}


