async function showInteractiveMap(location) {
    if (!location || !location.trim()) {
        alert("Location available nahi.");
        return;
    }

    const searchLocation = location.trim();

    try {
        const response = await fetch(
            `https://nominatim.openstreetmap.org/search?format=jsonv2&q=${encodeURIComponent(searchLocation)}&limit=1`
        );

        if (!response.ok) {
            throw new Error("Location search failed");
        }

        const results = await response.json();

        if (!results.length) {
            alert("Location map var sapadli nahi. Dusra address try kar.");
            return;
        }

        const lat = Number(results[0].lat);
        const lon = Number(results[0].lon);

        // Map container show kara
        const mapContainer = document.getElementById("map");
        mapContainer.style.display = "block";

        // Map first time create kara
        if (!osmMap) {
            osmMap = L.map("map");

            L.tileLayer(
                "https://{s}.tile.openstreetmap.org/{z}/{x}/{y}.png",
                {
                    attribution: "&copy; OpenStreetMap contributors"
                }
            ).addTo(osmMap);
        }

        // Location var map center kara
        osmMap.setView([lat, lon], 14);

        // Existing marker move kara, nahitar navin marker create kara
        if (osmMarker) {
            osmMarker.setLatLng([lat, lon]);
        } else {
            osmMarker = L.marker([lat, lon]).addTo(osmMap);
        }

        // Marker click kelyavar location show hoil
        osmMarker
            .bindPopup(`<b>Animal Location</b><br>${searchLocation}`)
            .openPopup();

        // Map layout refresh kara
        setTimeout(() => {
            osmMap.invalidateSize();
        }, 200);

        mapContainer.scrollIntoView({
            behavior: "smooth",
            block: "center"
        });

    } catch (error) {
        console.error("Map error:", error);
        alert("Map load zala nahi. Internet connection check kar.");
    }
}

function openMap(location) {
    if (!location || !location.trim()) {
        alert("Location available nahi.");
        return;
    }

    const searchLocation = decodeURIComponent(location);

    const mapUrl =
        `https://www.openstreetmap.org/search?query=${encodeURIComponent(searchLocation)}`;

    window.open(mapUrl, "_blank");
}

