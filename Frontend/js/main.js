const API_BASE = "https://pashubazar.onrender.com";

async function loadAnimals() {
    try {
        const response = await fetch(`${API_BASE}/api/animals`);
        const data = await response.json();

        if (!response.ok) {
            throw new Error(data.message || "Animals load hot nahit.");
        }

        A = (data.animals || []).map(animal => [
            animal.category || "",
            animal.breed || "",
            animal.age || "",
            animal.gender || "",
            animal.health || "",
            animal.vaccination || "",
            animal.location || "",
            `₹${Number(animal.price || 0).toLocaleString("en-IN")}`,
            animal.sellerMobile || "",
            animal.photo || "",
            animal._id || ""
        ]);

        render();
        renderFavorites();

    } catch (error) {
        console.error("Animal loading error:", error);
        alert("Animals load zale nahit. Backend ani MongoDB connection check kar.");
    }
}



